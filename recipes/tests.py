@pytest.mark.django_db
class TestRecipeNutritionCalculations:
    def test_cholesterol_calculated_from_mg_per_1000kcal(self):
        """cholesterol_mg está en mg/1000 kcal y debe convertirse a mg reales según kcal."""
        # Alimento con 250 kcal/100g y 400 mg colesterol por 1000 kcal.
        # 200 g aportan 500 kcal → 400 * (500 / 1000) = 200 mg de colesterol.
        egg = Food.objects.create(
            name="Huevo test",
            energy_kcal=Decimal("250.00"),
            proteins_g=Decimal("12.00"),
            cholesterol_mg=Decimal("400.00"),
        )
        recipe = Recipe.objects.create(name="Tortilla", servings=1)
        RecipeIngredient.objects.create(recipe=recipe, food=egg, quantity_g=Decimal("200.00"))

        nutrition = recipe.calculate_nutrition()
        assert nutrition["energy_kcal"] == pytest.approx(500.0)
        assert nutrition["proteins_g"] == pytest.approx(24.0)
        assert nutrition["cholesterol_mg"] == pytest.approx(200.0)

    def test_cholesterol_zero_when_energy_is_none(self):
        food = Food.objects.create(
            name="Sin kcal",
            energy_kcal=None,
            cholesterol_mg=Decimal("300.00"),
        )
        recipe = Recipe.objects.create(name="Test", servings=1)
        RecipeIngredient.objects.create(recipe=recipe, food=food, quantity_g=Decimal("100.00"))

        nutrition = recipe.calculate_nutrition()
        assert nutrition["cholesterol_mg"] == pytest.approx(0.0)

    def test_edible_portion_scales_nutrients_and_glycemic_load(self):
        """edible_portion (%) reduce el peso útil en nutrición y carga glucémica."""
        # Plátano con 70% porción comestible, 100 kcal/100g, 20g HC/100g, IG 50.
        # 200 g brutos → 140 g comestibles (factor 1.4):
        #   kcal = 140, carbs = 28 g, CG = 50 * 28 / 100 = 14.0
        banana = Food.objects.create(
            name="Plátano con piel",
            edible_portion=Decimal("70.00"),
            energy_kcal=Decimal("100.00"),
            carbohydrates_g=Decimal("20.00"),
            glycemic_index=Decimal("50.00"),
            cholesterol_mg=Decimal("100.00"),
        )
        recipe = Recipe.objects.create(name="Batido", servings=1)
        RecipeIngredient.objects.create(recipe=recipe, food=banana, quantity_g=Decimal("200.00"))

        nutrition = recipe.calculate_nutrition()
        cg = recipe.calculate_glycemic_load()

        assert nutrition["energy_kcal"] == pytest.approx(140.0)
        assert nutrition["carbohydrates_g"] == pytest.approx(28.0)
        # Colesterol sobre 140 kcal efectivas: 100 * 140 / 1000 = 14.0 mg
        assert nutrition["cholesterol_mg"] == pytest.approx(14.0)
        assert cg["total_cg"] == pytest.approx(14.0)
        assert cg["has_missing_ig"] is False

    def test_edible_portion_none_defaults_to_100_percent(self):
        rice = Food.objects.create(
            name="Arroz blanco",
            edible_portion=None,
            energy_kcal=Decimal("350.00"),
        )
        recipe = Recipe.objects.create(name="Arroz cocido", servings=1)
        RecipeIngredient.objects.create(recipe=recipe, food=rice, quantity_g=Decimal("100.00"))

        assert recipe.calculate_nutrition()["energy_kcal"] == pytest.approx(350.0)


