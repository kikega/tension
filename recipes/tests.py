@pytest.mark.django_db
class TestPhase2EnrichedModels:
    def test_eu_allergens_seeded(self):
        from nutrition.models import Allergen

        assert Allergen.objects.count() == 14
        assert Allergen.objects.filter(code="gluten").exists()
        assert Allergen.objects.filter(code="milk").exists()

    def test_slug_autogenerated_and_unique(self):
        r1 = Recipe.objects.create(name="Lentejas con Verduras", servings=2)
        r2 = Recipe.objects.create(name="Lentejas con Verduras", servings=4)
        assert r1.slug == "lentejas-con-verduras"
        assert r2.slug == "lentejas-con-verduras-2"

    def test_youtube_url_validation_and_embed_url(self):
        from django.core.exceptions import ValidationError
        from recipes.validators import extract_youtube_id, validate_youtube_url

        valid_urls = [
            "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
            "https://youtu.be/dQw4w9WgXcQ",
            "https://www.youtube.com/shorts/dQw4w9WgXcQ",
            "https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ",
        ]
        for url in valid_urls:
            validate_youtube_url(url)
            assert extract_youtube_id(url) == "dQw4w9WgXcQ"

        r = Recipe.objects.create(name="Con Vídeo", video_url="https://youtu.be/dQw4w9WgXcQ")
        assert r.youtube_embed_url == "https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ?rel=0"

        for bad_url in [
            "https://evil.example.com/watch?v=dQw4w9WgXcQ",
            "javascript:alert(1)",
            "https://www.youtube.com/watch?v=corto",
        ]:
            with pytest.raises(ValidationError):
                validate_youtube_url(bad_url)

    def test_household_measure_auto_computes_grams_and_display(self):
        from nutrition.models import HouseholdMeasure

        egg = Food.objects.create(name="Huevo M", energy_kcal=Decimal("155.00"))
        measure = HouseholdMeasure.objects.create(food=egg, name="huevo M", grams=Decimal("53.00"))
        recipe = Recipe.objects.create(name="Revuelto", servings=1)
        ing = RecipeIngredient.objects.create(
            recipe=recipe,
            food=egg,
            household_measure=measure,
            household_quantity=Decimal("2"),
            quantity_g=Decimal("0"),
        )
        assert ing.quantity_g == Decimal("106.00")
        assert "2 huevo M" in ing.display_quantity
        assert "106 g" in ing.display_quantity

    def test_allergens_propagate_from_ingredients_to_recipe(self):
        from nutrition.models import Allergen

        gluten = Allergen.objects.get(code="gluten")
        milk = Allergen.objects.get(code="milk")
        flour = Food.objects.create(name="Harina trigo", energy_kcal=Decimal("364.00"))
        flour.allergens.add(gluten)
        cheese = Food.objects.create(name="Queso fresco", energy_kcal=Decimal("174.00"))
        cheese.allergens.add(milk)

        recipe = Recipe.objects.create(name="Tosta con queso", servings=1)
        RecipeIngredient.objects.create(recipe=recipe, food=flour, quantity_g=Decimal("50"))
        RecipeIngredient.objects.create(recipe=recipe, food=cheese, quantity_g=Decimal("40"))

        codes = set(recipe.get_allergens().values_list("code", flat=True))
        assert codes == {"gluten", "milk"}

    def test_nutrition_cache_updates_via_signals_and_cooked_weight(self):
        from recipes.services.recipe_nutrition import calculate_recipe_nutrition_summary

        chicken = Food.objects.create(
            name="Pechuga pollo",
            energy_kcal=Decimal("165.00"),
            proteins_g=Decimal("31.00"),
            sodium_mg=Decimal("74.00"),
            potassium_mg=Decimal("256.00"),
        )
        recipe = Recipe.objects.create(
            name="Pollo a la plancha",
            servings=2,
            prep_time_min=5,
            cook_time_min=15,
            cooked_weight_g=Decimal("300.00"),  # pierde agua al cocinar (400g -> 300g)
        )
        assert recipe.total_time_min == 20

        ing = RecipeIngredient.objects.create(recipe=recipe, food=chicken, quantity_g=Decimal("400.00"))
        recipe.refresh_from_db()

        # 400 g = 660 kcal totales → 330 kcal/ración, 62 g proteína/ración
        assert recipe.cached_total_weight_g == Decimal("400.00")
        assert recipe.cached_kcal_per_serving == Decimal("330.00")
        assert recipe.cached_proteins_per_serving == Decimal("62.00")
        assert recipe.is_dash_friendly is True
        assert recipe.sodium_potassium_ratio == pytest.approx(0.29)

        # Valores por 100 g de plato terminado usan cooked_weight_g (300 g), no 400 g:
        # 660 kcal / 300 g * 100 = 220 kcal / 100 g
        summary = calculate_recipe_nutrition_summary(recipe)
        assert summary["per_100g"]["energy_kcal"] == pytest.approx(220.0)

        # Al cambiar servings a 4, la señal recalcula la caché automáticamente
        recipe.servings = 4
        recipe.save()
        recipe.refresh_from_db()
        assert recipe.cached_kcal_per_serving == Decimal("165.00")

        # Al actualizar el alimento, la señal recalcula las recetas afectadas
        chicken.energy_kcal = Decimal("200.00")
        chicken.save()
        recipe.refresh_from_db()
        assert recipe.cached_kcal_per_serving == Decimal("200.00")

        # Al borrar el ingrediente, la caché vuelve a 0
        ing.delete()
        recipe.refresh_from_db()
        assert recipe.cached_kcal_per_serving == Decimal("0.00")

    def test_groups_and_steps_ordering(self):
        from recipes.models import IngredientGroup, RecipeStep

        recipe = Recipe.objects.create(name="Guiso", servings=4)
        g2 = IngredientGroup.objects.create(recipe=recipe, name="Para la salsa", order=2)
        g1 = IngredientGroup.objects.create(recipe=recipe, name="Base", order=1)
        assert list(recipe.ingredient_groups.all()) == [g1, g2]

        s2 = RecipeStep.objects.create(recipe=recipe, order=2, instruction="Cocer", timer_seconds=900)
        s1 = RecipeStep.objects.create(recipe=recipe, order=1, instruction="Sofreír", tip="Fuego medio")
        assert list(recipe.steps.all()) == [s1, s2]
        assert s2.timer_minutes == 15.0


def _make_test_image(width: int = 2000, height: int = 1200, fmt: str = "JPEG", name: str = "plato.jpg"):
    from io import BytesIO
    from django.core.files.uploadedfile import SimpleUploadedFile
    from PIL import Image

    buf = BytesIO()
    img = Image.new("RGB", (width, height), color=(180, 90, 50))
    img.save(buf, format=fmt)
    content_type = "image/jpeg" if fmt == "JPEG" else f"image/{fmt.lower()}"
    return SimpleUploadedFile(name, buf.getvalue(), content_type=content_type)


@pytest.mark.django_db
class TestPhase3Multimedia:
    def test_recipe_media_generates_webp_variants_and_srcset(self, settings, tmp_path):
        from PIL import Image
        from recipes.models import RecipeMedia

        settings.MEDIA_ROOT = tmp_path
        recipe = Recipe.objects.create(name="Salmorejo", servings=2)
        media = RecipeMedia.objects.create(
            recipe=recipe,
            image=_make_test_image(2000, 1200, "JPEG", "salmorejo.jpg"),
            is_cover=True,
            alt_text="Bol de salmorejo con huevo",
        )

        assert media.image.name.endswith(".webp")
        assert media.image_medium.name.endswith(".webp")
        assert media.image_thumb.name.endswith(".webp")
        assert media.width == 1600
        assert media.height == 960

        with Image.open(media.image.path) as im:
            assert im.format == "WEBP"
            assert im.size == (1600, 960)
        with Image.open(media.image_medium.path) as im:
            assert im.size == (800, 480)
        with Image.open(media.image_thumb.path) as im:
            assert im.size == (400, 240)

        assert "400w" in media.srcset
        assert "800w" in media.srcset
        assert "1600w" in media.srcset
        assert recipe.cover_media == media

    def test_small_image_is_not_upscaled(self, settings, tmp_path):
        from recipes.models import RecipeMedia

        settings.MEDIA_ROOT = tmp_path
        recipe = Recipe.objects.create(name="Tostada", servings=1)
        media = RecipeMedia.objects.create(
            recipe=recipe,
            image=_make_test_image(300, 200, "PNG", "peque.png"),
        )
        assert media.width == 300
        assert media.height == 200

    def test_only_one_cover_photo_per_recipe(self, settings, tmp_path):
        from recipes.models import RecipeMedia

        settings.MEDIA_ROOT = tmp_path
        recipe = Recipe.objects.create(name="Paella", servings=4)
        m1 = RecipeMedia.objects.create(recipe=recipe, image=_make_test_image(600, 400), is_cover=True)
        m2 = RecipeMedia.objects.create(recipe=recipe, image=_make_test_image(600, 400), is_cover=True)

        m1.refresh_from_db()
        m2.refresh_from_db()
        assert m1.is_cover is False
        assert m2.is_cover is True
        assert recipe.cover_media == m2

    def test_invalid_file_and_svg_rejected(self):
        from django.core.exceptions import ValidationError
        from django.core.files.uploadedfile import SimpleUploadedFile
        from recipes.services.media_processor import validate_uploaded_image

        fake_svg = SimpleUploadedFile("xss.svg", b"<svg><script>alert(1)</script></svg>", content_type="image/svg+xml")
        with pytest.raises(ValidationError):
            validate_uploaded_image(fake_svg)

        corrupt = SimpleUploadedFile("bad.jpg", b"not an image at all", content_type="image/jpeg")
        with pytest.raises(ValidationError):
            validate_uploaded_image(corrupt)

    def test_deleting_media_removes_files_from_disk(self, settings, tmp_path):
        from pathlib import Path
        from recipes.models import RecipeMedia

        settings.MEDIA_ROOT = tmp_path
        recipe = Recipe.objects.create(name="Gazpacho", servings=2)
        media = RecipeMedia.objects.create(recipe=recipe, image=_make_test_image(900, 600))
        paths = [Path(media.image.path), Path(media.image_medium.path), Path(media.image_thumb.path)]
        assert all(p.exists() for p in paths)

        media.delete()
        assert all(not p.exists() for p in paths)

    def test_recipe_step_photo_processed_and_cleaned_up(self, settings, tmp_path):
        from pathlib import Path
        from recipes.models import RecipeStep

        settings.MEDIA_ROOT = tmp_path
        recipe = Recipe.objects.create(name="Tortilla", servings=2)
